/// The glyph centred in a `box`-sized square, one rect per run of lit pixels.
/// `snap` moves it onto whole device pixels; see snapOffset.
pub fn commands(arena: std.mem.Allocator, glyph: Glyph, box: f32, snap: [2]f32, color: [4]f32) ![]const DrawCmd {
    const rows = bitmap(glyph);
    const width: f32 = @floatFromInt(rows[0].len);
    const height: f32 = @floatFromInt(rows.len);
    const origin = [2]f32{ @floor((box - width) / 2) + snap[0], @floor((box - height) / 2) + snap[1] };
    var list: std.ArrayList(DrawCmd) = .empty;
    for (rows, 0..) |row, y| {
        var x: usize = 0;
        while (x < row.len) {
            if (row[x] != '#') {
                x += 1;
                continue;
            }
            const start = x;
            while (x < row.len and row[x] == '#') x += 1;
            try list.append(arena, .{ .fill_rect = .{
                .x = origin[0] + @as(f32, @floatFromInt(start)),
                .y = origin[1] + @as(f32, @floatFromInt(y)),
                .w = @floatFromInt(x - start),
                .h = 1,
                .color = color,
            } });
        }
    }
    return list.items;
}

/// How far to shift a canvas's drawing so its pixels land on whole device pixels, from where it was laid out last frame.
pub fn snapOffset(context: *ui.Frame, key: ui.Key) ![2]f32 {
    const ui_state = context.ui();
    const measured = try ui_state.state.getOrCreate(.measured, ui_state.allocator, key.hash());
    const scale = ui_state.content_scale;
    const x = measured.box.x();
    const y = measured.box.y();
    return .{ @round(x * scale) / scale - x, @round(y * scale) / scale - y };
}
